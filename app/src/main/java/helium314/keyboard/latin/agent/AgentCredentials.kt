package helium314.keyboard.latin.agent

import android.content.Context
import android.os.Build
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.AtomicFile
import org.json.JSONObject
import java.io.File
import java.io.FileNotFoundException
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Separate from all normal/backup-exported preferences; unavailable during Direct Boot. */
class AgentCredentials(context: Context) {
    private val file = AtomicFile(File(context.noBackupFilesDir, "hermes-agent.enc"))
    private val userManager = context.getSystemService(Context.USER_SERVICE) as android.os.UserManager

    private fun requireUnlocked() {
        check(Build.VERSION.SDK_INT >= 23)
        check(Build.VERSION.SDK_INT < 24 || userManager.isUserUnlocked)
    }

    // Deliberately not a data class: no autogenerated toString containing credentials.
    class Config(val base: String, val token: String, val enabled: Boolean)

    fun load(): Config? {
        requireUnlocked()
        // openRead must run even without the base file: AtomicFile can recover its .bak.
        val input = try { file.openRead() } catch (e: FileNotFoundException) {
            if (!file.baseFile.exists() && !File(file.baseFile.path + ".bak").exists()) return null
            throw e
        }
        val bytes = input.use { input ->
            val data = ByteArray(16385)
            var size = 0
            while (size < data.size) {
                val n = input.read(data, size, data.size - size)
                if (n < 0) break
                size += n
            }
            require(size in 29..16384)
            data.copyOf(size)
        }
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.DECRYPT_MODE, key(false), GCMParameterSpec(128, bytes.copyOfRange(0, 12)))
        val json = JSONObject(String(cipher.doFinal(bytes.copyOfRange(12, bytes.size)), Charsets.UTF_8))
        val config = Config(json.getString("base"), json.getString("token"), json.getBoolean("enabled"))
        AgentProtocol.endpoint(config.base)
        require(AgentProtocol.validToken(config.token))
        return config
    }

    fun save(config: Config) {
        requireUnlocked()
        AgentProtocol.endpoint(config.base)
        require(AgentProtocol.validToken(config.token))
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.ENCRYPT_MODE, key(true))
        val plain = JSONObject().put("base", config.base).put("token", config.token)
            .put("enabled", config.enabled).toString().toByteArray(Charsets.UTF_8)
        val encrypted = try { cipher.doFinal(plain) } finally { plain.fill(0) }
        val output = file.startWrite()
        try {
            output.write(cipher.iv)
            output.write(encrypted)
            file.finishWrite(output)
        } catch (e: Exception) {
            file.failWrite(output)
            throw e
        }
    }

    fun clear() {
        requireUnlocked()
        file.delete()
        KeyStore.getInstance("AndroidKeyStore").apply { load(null); deleteEntry(ALIAS) }
    }

    private fun key(create: Boolean): SecretKey {
        // Keep the API guard local so lint and runtime both enforce the Keystore minimum.
        if (Build.VERSION.SDK_INT < 23) throw IllegalStateException("Keystore requires Android 6")
        val store = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
        (store.getKey(ALIAS, null) as? SecretKey)?.let { return it }
        check(create)
        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, "AndroidKeyStore")
        generator.init(KeyGenParameterSpec.Builder(ALIAS, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM).setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setRandomizedEncryptionRequired(true).build())
        return generator.generateKey()
    }

    companion object {
        private const val ALIAS = "hermes-agent-token-v1"

        /** Blank token permits only revoking opt-in at the exact saved URL, not enabling or moving it. */
        internal fun configurationForSave(base: String, token: String, enabled: Boolean, previous: Config?): Config {
            AgentProtocol.endpoint(base)
            if (token.isNotEmpty()) {
                require(AgentProtocol.validToken(token))
                return Config(base, token, enabled)
            }
            require(!enabled && previous != null && base == previous.base)
            return Config(base, previous.token, false)
        }
    }
}
